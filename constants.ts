const inferUnit = (description: string): string => {
  const d = description.toUpperCase();
  if (d.includes('LUVA') || d.includes('BOTA') || d.includes('CALÇADO') || d.includes('BOTINA') || d.includes('PERNEIRA') || d.includes('MANGOTE')) return 'PAR';
  if (d.includes('TRAVA QUEDA') || d.includes('TALABARTE') || d.includes('CINTO') || d.includes('MOSQUETÃO')) return 'UN';
  if (d.includes('METROS') || d.includes('CABO') || d.includes('CORDA')) return 'MT';
  return 'UN';
};

